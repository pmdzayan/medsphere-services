import type { Locale } from '@/lib/i18n';

export interface PublicSearchCopy {
  title: string;
  description: string;
  medicineName: string;
  placeholder: string;
  searching: string;
  search: string;
  unavailable: string;
  pharmacyNotFound: string;
  somethingWrong: string;
  noMatches: string;
  noMatchesFor: (term: string) => string;
  inStock: string;
  outOfStock: string;
  prescriptionRequired: string;
  contactToReserve: (provider: string) => string;
  missingTitle: string;
  missingDescription: string;
}

type StaticCopy = Omit<PublicSearchCopy, 'noMatchesFor' | 'contactToReserve'> & {
  noMatchesFor: string;
  contactToReserve: string;
};

function create(values: readonly string[]): PublicSearchCopy {
  const [
    title,
    description,
    medicineName,
    placeholder,
    searching,
    search,
    unavailable,
    pharmacyNotFound,
    somethingWrong,
    noMatches,
    noMatchesFor,
    inStock,
    outOfStock,
    prescriptionRequired,
    contactToReserve,
    missingTitle,
    missingDescription,
  ] = values as unknown as readonly [
    string,
    string,
    string,
    string,
    string,
    string,
    string,
    string,
    string,
    string,
    string,
    string,
    string,
    string,
    string,
    string,
    string,
  ];
  return {
    title,
    description,
    medicineName,
    placeholder,
    searching,
    search,
    unavailable,
    pharmacyNotFound,
    somethingWrong,
    noMatches,
    inStock,
    outOfStock,
    prescriptionRequired,
    noMatchesFor: (term) => noMatchesFor.replace('{term}', term),
    contactToReserve: (provider) => contactToReserve.replace('{provider}', provider),
    missingTitle,
    missingDescription,
  };
}

