export function isLocale(value: string | null): value is Locale {
  return localeOptions.some((option) => option.code === value);
}

export function getLocaleDirection(locale: Locale): LocaleDirection {
  return localeOptions.find((option) => option.code === locale)?.dir ?? 'ltr';
}

export function translate(locale: Locale, key: TranslationKey): string {
  return localeMessages[locale]?.[key] ?? englishMessages[key];
}
